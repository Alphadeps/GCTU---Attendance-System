/**
 * Check pending reports in production database using DIRECT connection
 */

// Override DATABASE_URL with DIRECT_URL BEFORE loading dotenv
const fs = require('fs');
const path = require('path');

// Read .env file
const envPath = path.join(__dirname, '.env');
const envContent = fs.readFileSync(envPath, 'utf8');

// Parse and set DIRECT_URL as DATABASE_URL
const lines = envContent.split('\n');
for (const line of lines) {
  if (line.startsWith('DIRECT_URL=')) {
    const directUrl = line.substring('DIRECT_URL='.length).trim().replace(/^["']|["']$/g, '');
    process.env.DATABASE_URL = directUrl;
    console.log('✓ Using DIRECT_URL for faster connection\n');
    break;
  }
}

const prisma = require('./src/lib/prisma');

async function checkPendingReports() {
  console.log('🔍 Checking pending reports in production (DIRECT connection)...\n');

  try {
    // Count reports by status
    const pendingCount = await prisma.officialReport.count({
      where: { status: 'PENDING_SIGNATURE' }
    });

    const approvedCount = await prisma.officialReport.count({
      where: { status: 'APPROVED' }
    });

    const totalCount = await prisma.officialReport.count();

    console.log('📊 Report Status Summary:');
    console.log(`   Pending Signature: ${pendingCount}`);
    console.log(`   Approved: ${approvedCount}`);
    console.log(`   Total: ${totalCount}\n`);

    // Get details of pending reports
    if (pendingCount > 0) {
      console.log('📋 Pending Reports Details:');
      const pendingReports = await prisma.officialReport.findMany({
        where: { status: 'PENDING_SIGNATURE' },
        include: {
          class: { include: { programme: true } },
          course: true,
          generatedBy: { select: { username: true } }
        }
      });

      pendingReports.forEach((r, i) => {
        console.log(`\n   ${i + 1}. Report ID: ${r.id}`);
        console.log(`      Course: ${r.course.name} (${r.course.code})`);
        console.log(`      Class: ${r.class.displayName}`);
        console.log(`      Programme: ${r.class.programme.name}`);
        console.log(`      Generated by: ${r.generatedBy.username}`);
        console.log(`      Created: ${r.createdAt}`);
      });
    }

    // Get details of approved reports
    if (approvedCount > 0) {
      console.log('\n\n✅ Approved Reports Details:');
      const approvedReports = await prisma.officialReport.findMany({
        where: { status: 'APPROVED' },
        include: {
          class: { include: { programme: true } },
          course: true,
          signedBy: { select: { username: true } }
        }
      });

      approvedReports.forEach((r, i) => {
        console.log(`\n   ${i + 1}. Report ID: ${r.id}`);
        console.log(`      Course: ${r.course.name} (${r.course.code})`);
        console.log(`      Class: ${r.class.displayName}`);
        console.log(`      Programme: ${r.class.programme.name}`);
        console.log(`      Signed by: ${r.signedBy?.username || 'N/A'}`);
        console.log(`      Signed at: ${r.signedAt || 'N/A'}`);
      });
    }

    console.log('\n✅ Check complete!');

  } catch (error) {
    console.error('❌ Error:', error.message);
    console.error(error);
  } finally {
    await prisma.$disconnect();
    process.exit(0);
  }
}

checkPendingReports();
