/**
 * Debug lecturer assignments and pending reports
 */

// Override DATABASE_URL with DIRECT_URL BEFORE loading dotenv
const fs = require('fs');
const path = require('path');

// Read .env file
const envPath = path.join(__dirname, '.env');
const envContent = fs.readFileSync(envPath, 'utf8');

// Parse and set DIRECT_URL as DATABASE_URL
const lines = envContent.split('\n');
for (const line of lines) {
  if (line.startsWith('DIRECT_URL=')) {
    const directUrl = line.substring('DIRECT_URL='.length).trim().replace(/^["']|["']$/g, '');
    process.env.DATABASE_URL = directUrl;
    console.log('✓ Using DIRECT_URL for faster connection\n');
    break;
  }
}

const prisma = require('./src/lib/prisma');

async function debugLecturerAssignments() {
  console.log('🔍 Debugging Lecturer Assignments and Pending Reports\n');

  try {
    // 1. Get all pending reports
    console.log('📋 PENDING REPORTS:');
    const pendingReports = await prisma.officialReport.findMany({
      where: { status: 'PENDING_SIGNATURE' },
      include: {
        class: { include: { programme: true } },
        course: true,
        generatedBy: { select: { id: true, username: true, role: true } }
      }
    });

    if (pendingReports.length === 0) {
      console.log('   No pending reports found.\n');
    } else {
      pendingReports.forEach((r, i) => {
        console.log(`\n   ${i + 1}. Report ID: ${r.id}`);
        console.log(`      Course: ${r.course.name} (${r.course.code})`);
        console.log(`      Course ID: ${r.courseId}`);
        console.log(`      Class: ${r.class.displayName}`);
        console.log(`      Class ID: ${r.classId}`);
        console.log(`      Programme: ${r.class.programme.name}`);
        console.log(`      Generated by: ${r.generatedBy.username} (${r.generatedBy.role})`);
        console.log(`      Status: ${r.status}`);
      });
    }

    // 2. Get all lecturers
    console.log('\n\n👨‍🏫 ALL LECTURERS:');
    const lecturers = await prisma.user.findMany({
      where: { role: 'LECTURER' },
      select: { id: true, username: true, isActive: true }
    });

    if (lecturers.length === 0) {
      console.log('   No lecturers found.\n');
    } else {
      lecturers.forEach((l, i) => {
        console.log(`   ${i + 1}. ${l.username} (ID: ${l.id}) - Active: ${l.isActive}`);
      });
    }

    // 3. Get all lecturer assignments
    console.log('\n\n📚 LECTURER ASSIGNMENTS:');
    const assignments = await prisma.lecturerAssignment.findMany({
      include: {
        lecturer: { select: { username: true } },
        class: { select: { displayName: true } },
        course: { select: { name: true, code: true } }
      }
    });

    if (assignments.length === 0) {
      console.log('   No lecturer assignments found.\n');
    } else {
      assignments.forEach((a, i) => {
        console.log(`\n   ${i + 1}. Assignment ID: ${a.id}`);
        console.log(`      Lecturer: ${a.lecturer.username} (ID: ${a.lecturerId})`);
        console.log(`      Course: ${a.course.name} (${a.course.code})`);
        console.log(`      Course ID: ${a.courseId}`);
        console.log(`      Class: ${a.class.displayName}`);
        console.log(`      Class ID: ${a.classId}`);
      });
    }

    // 4. Check if pending reports match any lecturer assignments
    console.log('\n\n🔗 MATCHING PENDING REPORTS TO LECTURERS:');
    if (pendingReports.length === 0) {
      console.log('   No pending reports to match.\n');
    } else {
      for (const report of pendingReports) {
        console.log(`\n   Report: ${report.course.code} - ${report.class.displayName}`);
        console.log(`   Looking for: classId=${report.classId}, courseId=${report.courseId}`);
        
        const matchingAssignments = assignments.filter(a => 
          a.classId === report.classId && a.courseId === report.courseId
        );

        if (matchingAssignments.length === 0) {
          console.log('   ❌ NO MATCHING LECTURER ASSIGNMENT FOUND!');
          console.log('   This is why the lecturer cannot see this report.');
        } else {
          console.log(`   ✅ Found ${matchingAssignments.length} matching assignment(s):`);
          matchingAssignments.forEach(a => {
            console.log(`      - Lecturer: ${a.lecturer.username} (ID: ${a.lecturerId})`);
          });
        }
      }
    }

    console.log('\n✅ Debug complete!');

  } catch (error) {
    console.error('❌ Error:', error.message);
    console.error(error);
  } finally {
    await prisma.$disconnect();
    process.exit(0);
  }
}

debugLecturerAssignments();
